class Database:
    def __init__(self, db_file=DB_FILE):
        self.conn = sqlite3.connect(db_file)
        self.conn.execute("PRAGMA foreign_keys = ON")
        self._create_tables()

    def _create_tables(self):
        cur = self.conn.cursor()
        cur.execute("""
            CREATE TABLE IF NOT EXISTS rooms (
                room_id INTEGER PRIMARY KEY AUTOINCREMENT,
                room_number TEXT UNIQUE NOT NULL,
                room_type TEXT NOT NULL,
                price_per_night REAL NOT NULL,
                status TEXT NOT NULL DEFAULT 'Available'
            )
        """)
        cur.execute("""
            CREATE TABLE IF NOT EXISTS guests (
                guest_id INTEGER PRIMARY KEY AUTOINCREMENT,
                name TEXT NOT NULL,
                phone TEXT,
                email TEXT
            )
        """)
        cur.execute("""
            CREATE TABLE IF NOT EXISTS bookings (
                booking_id INTEGER PRIMARY KEY AUTOINCREMENT,
                room_id INTEGER NOT NULL,
                guest_id INTEGER NOT NULL,
                check_in TEXT NOT NULL,
                check_out TEXT,
                status TEXT NOT NULL DEFAULT 'Active',
                total_bill REAL,
                FOREIGN KEY (room_id) REFERENCES rooms(room_id),
                FOREIGN KEY (guest_id) REFERENCES guests(guest_id)
            )
        """)
        self.conn.commit()

    # ---- Rooms ----
    def add_room(self, number, rtype, price):
        self.conn.execute(
            "INSERT INTO rooms (room_number, room_type, price_per_night) VALUES (?, ?, ?)",
            (number, rtype, price),
        )
        self.conn.commit()

    def get_rooms(self):
        return self.conn.execute("SELECT * FROM rooms ORDER BY room_number").fetchall()

    def get_available_rooms(self):
        return self.conn.execute(
            "SELECT * FROM rooms WHERE status = 'Available' ORDER BY room_number"
        ).fetchall()

    def set_room_status(self, room_id, status):
        self.conn.execute("UPDATE rooms SET status = ? WHERE room_id = ?", (status, room_id))
        self.conn.commit()

    def delete_room(self, room_id):
        self.conn.execute("DELETE FROM rooms WHERE room_id = ?", (room_id,))
        self.conn.commit()

    # ---- Guests ----
    def add_guest(self, name, phone, email):
        cur = self.conn.execute(
            "INSERT INTO guests (name, phone, email) VALUES (?, ?, ?)",
            (name, phone, email),
        )
        self.conn.commit()
        return cur.lastrowid

    def get_guests(self):
        return self.conn.execute("SELECT * FROM guests ORDER BY name").fetchall()

    def delete_guest(self, guest_id):
        self.conn.execute("DELETE FROM guests WHERE guest_id = ?", (guest_id,))
        self.conn.commit()

    # ---- Bookings ----
    def add_booking(self, room_id, guest_id, check_in):
        cur = self.conn.execute(
            "INSERT INTO bookings (room_id, guest_id, check_in, status) VALUES (?, ?, ?, 'Active')",
            (room_id, guest_id, check_in),
        )
        self.conn.commit()
        self.set_room_status(room_id, "Occupied")
        return cur.lastrowid

    def get_active_bookings(self):
        return self.conn.execute("""
            SELECT b.booking_id, r.room_number, g.name, b.check_in, r.price_per_night, b.room_id, g.guest_id
            FROM bookings b
            JOIN rooms r ON b.room_id = r.room_id
            JOIN guests g ON b.guest_id = g.guest_id
            WHERE b.status = 'Active'
            ORDER BY b.check_in
        """).fetchall()

    def get_all_bookings(self):
        return self.conn.execute("""
            SELECT b.booking_id, r.room_number, g.name, b.check_in, b.check_out, b.status, b.total_bill
            FROM bookings b
            JOIN rooms r ON b.room_id = r.room_id
            JOIN guests g ON b.guest_id = g.guest_id
            ORDER BY b.booking_id DESC
        """).fetchall()

    def checkout_booking(self, booking_id, room_id, check_out, total_bill):
        self.conn.execute(
            "UPDATE bookings SET check_out = ?, status = 'Completed', total_bill = ? WHERE booking_id = ?",
            (check_out, total_bill, booking_id),
        )
        self.set_room_status(room_id, "Available")
        self.conn.commit()


