class RoomsScreen(Screen):
    def __init__(self, **kwargs):
        super().__init__(**kwargs)
        root = BoxLayout(orientation="vertical", padding=dp(10), spacing=dp(10))

        form = GridLayout(cols=4, size_hint_y=None, height=dp(50), spacing=dp(6))
        self.number_input = TextInput(hint_text="Room Number", multiline=False)
        self.price_input = TextInput(hint_text="Price/Night", multiline=False, input_filter="float")
        self.type_spinner = Spinner(text="Single", values=["Single", "Double", "Suite", "Deluxe"])
        add_btn = Button(text="Add Room")
        add_btn.bind(on_release=self.add_room)

        form.add_widget(self.number_input)
        form.add_widget(self.type_spinner)
        form.add_widget(self.price_input)
        form.add_widget(add_btn)
        root.add_widget(form)

        self.table = TableView(headers=["ID", "Room #", "Type", "Price/Night", "Status"])
        root.add_widget(self.table)

        self.selected_id = None
        delete_btn = Button(text="Delete Selected Room", size_hint_y=None, height=dp(40))
        delete_btn.bind(on_release=self.delete_room)
        root.add_widget(delete_btn)

        self.add_widget(root)

    def on_pre_enter(self, *args):
        self.refresh()

    def add_room(self, instance):
        number = self.number_input.text.strip()
        rtype = self.type_spinner.text
        price = self.price_input.text.strip()

        if not number or not price:
            show_popup("Missing Info", "Please enter room number and price.")
            return
        try:
            price_val = float(price)
        except ValueError:
            show_popup("Invalid Price", "Price must be a number.")
            return
        try:
            db.add_room(number, rtype, price_val)
        except sqlite3.IntegrityError:
            show_popup("Duplicate", f"Room {number} already exists.")
            return

        self.number_input.text = ""
        self.price_input.text = ""
        self.refresh()

    def select_row(self, room_id):
        self.selected_id = room_id

    def delete_room(self, instance):
        if not self.selected_id:
            show_popup("No Selection", "Tap 'Select' next to a room first.")
            return

        def do_delete():
            db.delete_room(self.selected_id)
            self.selected_id = None
            self.refresh()

        confirm_popup("Confirm", "Delete this room? This cannot be undone.", do_delete)

    def refresh(self):
        self.table.clear_rows()
        for room in db.get_rooms():
            room_id, number, rtype, price, status = room
            self.table.add_row(
                [room_id, number, rtype, f"${price:.2f}", status],
                on_select=self.select_row,
            )


